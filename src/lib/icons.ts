/**
 * Katalog ikon pro projekty a úkoly.
 *
 * Ikona se ukládá jako string:
 *  - emoji rovnou ("💪")
 *  - kreslená ikona s předponou ("lucide:Dumbbell")
 *
 * Díky předponě je starý zápis (holé emoji) pořád platný a nic se nemigruje.
 * Samotné komponenty ikon žijí v `components/ui/icon-picker.tsx` - tady je jen
 * data a jména, aby šel katalog použít i bez Reactu.
 */

export const LUCIDE_PREFIX = "lucide:";

/** "lucide:Dumbbell" -> "Dumbbell", emoji -> null. */
export function lucideNameOf(icon: string): string | null {
  return icon.startsWith(LUCIDE_PREFIX) ? icon.slice(LUCIDE_PREFIX.length) : null;
}

export function lucideRef(name: string): string {
  return `${LUCIDE_PREFIX}${name}`;
}

/**
 * Klíčová slova se hledají bez diakritiky - uživatel píše "kava", ne "káva".
 */
export function normalizeQuery(value: string): string {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .trim();
}

export interface IconEntry {
  /** Emoji znak nebo jméno lucide ikony. */
  value: string;
  /** Slova pro hledání, oddělená mezerou. */
  keywords: string;
}

export interface IconGroup {
  label: string;
  items: IconEntry[];
}

function group(label: string, pairs: [string, string][]): IconGroup {
  return { label, items: pairs.map(([value, keywords]) => ({ value, keywords })) };
}

