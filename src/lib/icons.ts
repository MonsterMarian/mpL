/** Všechny položky jednoho katalogu na plocho - pro hledání. */
export function flattenGroups(groups: IconGroup[]): IconEntry[] {
  return groups.flatMap((g) => g.items);
}

/** Filtr katalogu podle dotazu; prázdný dotaz vrátí skupiny nedotčené. */
export function filterGroups(groups: IconGroup[], query: string): IconGroup[] {
  const q = normalizeQuery(query);
  if (!q) return groups;
  return groups
    .map((g) => ({
      label: g.label,
      items: g.items.filter(
        (i) => i.keywords.includes(q) || normalizeQuery(i.value).includes(q),
      ),
    }))
    .filter((g) => g.items.length > 0);
}
